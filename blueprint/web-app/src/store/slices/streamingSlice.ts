// Reducer function (simplified version without Redux Toolkit)
// Define a union type for all possible action payloads
type StreamingAction =
  | { type: typeof STREAMING_ACTIONS.SET_STREAM_READY; payload: boolean }
  | { type: typeof STREAMING_ACTIONS.SET_CONNECTING; payload: boolean }
  | { type: typeof STREAMING_ACTIONS.SET_CONNECTED; payload: boolean }
  | {
      type: typeof STREAMING_ACTIONS.SET_STREAM_CONFIG;
      payload: StreamConnectionConfig;
    }
  | {
      type: typeof STREAMING_ACTIONS.UPDATE_STREAM_SETTINGS;
      payload: Partial<{
        width: number;
        height: number;
        fps: number;
        nativeTouchEvents: boolean;
      }>;
    }
  | { type: typeof STREAMING_ACTIONS.SET_AUDIO_MUTED; payload: boolean }
  | { type: typeof STREAMING_ACTIONS.SET_VIDEO_MUTED; payload: boolean }
  | { type: typeof STREAMING_ACTIONS.SET_MICROPHONE_ENABLED; payload: boolean }
  | {
      type: typeof STREAMING_ACTIONS.UPDATE_CONNECTION_QUALITY;
      payload: StreamingState['connectionQuality'];
    }
  | {
      type: typeof STREAMING_ACTIONS.UPDATE_STREAM_METRICS;
      payload: { latency?: number; bitrate?: number; frameRate?: number };
    }
  | { type: typeof STREAMING_ACTIONS.SET_CONNECTION_ERROR; payload: string }
  | { type: typeof STREAMING_ACTIONS.CLEAR_CONNECTION_ERROR }
  | { type: typeof STREAMING_ACTIONS.INCREMENT_RECONNECT_ATTEMPTS }
  | { type: typeof STREAMING_ACTIONS.RESET_RECONNECT_ATTEMPTS }
  | { type: typeof STREAMING_ACTIONS.ADD_STREAM_EVENT; payload: StreamEvent }
  | { type: typeof STREAMING_ACTIONS.CLEAR_STREAM_EVENTS }
  | { type: typeof STREAMING_ACTIONS.RESET_STREAMING_STATE };

// Type guard to check if action is StreamingAction
function isStreamingAction(action: unknown): action is StreamingAction {
  if (action === null || typeof action !== 'object' || !('type' in action)) {
    return false;
  }
  const actionType = (action as { type: unknown }).type;
  return typeof actionType === 'string' &&
         (Object.values(STREAMING_ACTIONS) as string[]).includes(actionType);
}

export const streamingReducer = (
  state: StreamingState = initialState,
  action: unknown
): StreamingState => {
  // Only process known streaming actions
  if (!isStreamingAction(action)) {
    return state;
  }

  switch (action.type) {
    case STREAMING_ACTIONS.SET_STREAM_READY:
      return {
        ...state,
        streamReady: action.payload,
      };

    case STREAMING_ACTIONS.SET_CONNECTING:
      return {
        ...state,
        isConnecting: action.payload,
        lastConnectionAttempt: action.payload
          ? Date.now()
          : state.lastConnectionAttempt,
      };

    case STREAMING_ACTIONS.SET_CONNECTED:
      return {
        ...state,
        isConnected: action.payload,
        isConnecting: false,
        connectionError: action.payload ? null : state.connectionError,
        reconnectAttempts: action.payload ? 0 : state.reconnectAttempts,
      };

    case STREAMING_ACTIONS.SET_STREAM_CONFIG:
      return {
        ...state,
        ...action.payload,
      };

    case STREAMING_ACTIONS.UPDATE_STREAM_SETTINGS:
      return {
        ...state,
        ...action.payload,
      };

    case STREAMING_ACTIONS.SET_AUDIO_MUTED:
      return {
        ...state,
        audioMuted: action.payload,
      };

    case STREAMING_ACTIONS.SET_VIDEO_MUTED:
      return {
        ...state,
        videoMuted: action.payload,
      };

    case STREAMING_ACTIONS.SET_MICROPHONE_ENABLED:
      return {
        ...state,
        microphoneEnabled: action.payload,
      };

    case STREAMING_ACTIONS.UPDATE_CONNECTION_QUALITY:
      return {
        ...state,
        connectionQuality: action.payload,
      };

    case STREAMING_ACTIONS.UPDATE_STREAM_METRICS:
      return {
        ...state,
        ...action.payload,
      };

    case STREAMING_ACTIONS.SET_CONNECTION_ERROR:
      return {
        ...state,
        connectionError: action.payload,
        isConnecting: false,
      };

    case STREAMING_ACTIONS.CLEAR_CONNECTION_ERROR:
      return {
        ...state,
        connectionError: null,
      };

    case STREAMING_ACTIONS.INCREMENT_RECONNECT_ATTEMPTS:
      return {
        ...state,
        reconnectAttempts: state.reconnectAttempts + 1,
      };

    case STREAMING_ACTIONS.RESET_RECONNECT_ATTEMPTS:
      return {
        ...state,
        reconnectAttempts: 0,
      };

    case STREAMING_ACTIONS.ADD_STREAM_EVENT:
      return {
        ...state,
        streamEvents: [
          ...state.streamEvents.slice(-49), // Keep last 50 events
          action.payload,
        ],
      };

    case STREAMING_ACTIONS.CLEAR_STREAM_EVENTS:
      return {
        ...state,
        streamEvents: [],
      };

    case STREAMING_ACTIONS.RESET_STREAMING_STATE:
      return initialState;

    default:
      return state;
  }
};

// Selectors
export const selectStreamReady = (state: { streaming: StreamingState }) =>
  state.streaming.streamReady;
export const selectIsConnected = (state: { streaming: StreamingState }) =>
  state.streaming.isConnected;
