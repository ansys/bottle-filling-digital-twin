  state.streaming.isConnecting;
export const selectConnectionQuality = (state: { streaming: StreamingState }) =>
  state.streaming.connectionQuality;
export const selectStreamMetrics = (state: { streaming: StreamingState }) => ({
  latency: state.streaming.latency,
  bitrate: state.streaming.bitrate,
  frameRate: state.streaming.frameRate,
});
export const selectStreamEvents = (state: { streaming: StreamingState }) =>
  state.streaming.streamEvents;
export const selectConnectionError = (state: { streaming: StreamingState }) =>
  state.streaming.connectionError;

export default streamingReducer;
