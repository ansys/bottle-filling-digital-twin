/**
 * Streaming Slice
 *
 * Manages streaming-related state including WebRTC connection, media settings, and stream control
 */

// Note: This is a TypeScript implementation without Redux Toolkit to avoid dependencies
// In a real implementation, you would install @reduxjs/toolkit and react-redux

// Streaming state interface
export interface StreamingState {
  // Stream readiness and connection
  streamReady: boolean;
  isConnecting: boolean;
  isConnected: boolean;

  // WebRTC configuration
  signalingServer: string;
  signalingPort: number;
  mediaServer: string;
  mediaPort: number;
  backendUrl: string;
  accessToken: string;

  // Stream configuration
  videoElementId: string;
  audioElementId: string;
  width: number;
  height: number;
  fps: number;
  nativeTouchEvents: boolean;

  // Media settings
  audioMuted: boolean;
  videoMuted: boolean;
  microphoneEnabled: boolean;

  // Stream quality and performance
  connectionQuality: 'excellent' | 'good' | 'fair' | 'poor' | 'unknown';
  latency: number; // in milliseconds
  bitrate: number; // in kbps
  frameRate: number;

  // Error handling
  connectionError: string | null;
  lastConnectionAttempt: number | null;
  reconnectAttempts: number;
  maxReconnects: number;

  // Stream events log
  streamEvents: StreamEvent[];
}

export interface StreamEvent {
  timestamp: number;
  type: 'info' | 'warning' | 'error';
  action: string;
  status: string;
  message?: string;
  data?: unknown;
}

// Stream connection configuration interface for Redux state
export interface StreamConnectionConfig {
  signalingServer: string;
  signalingPort: number;
  mediaServer: string;
  mediaPort: number;
  backendUrl: string;
  sessionId: string;
  accessToken?: string;
  width?: number;
  height?: number;
  fps?: number;
}

